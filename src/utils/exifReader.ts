import exifr from 'exifr';
import { ExifData } from '../types.ts';
import { formatXiaomiDate } from './watermark.ts';

export interface ExifParseResult {
  exif: ExifData;
  dateStr: string;
  model: string;
  isAiEstimated: boolean;
  lensModel?: string;
}

/**
 * Intelligent Xiaomi Leica camera parameter estimator for AI-generated images
 * or photos with stripped/missing EXIF metadata.
 */
export function estimateAiExif(details?: {
  width?: number;
  height?: number;
  filename?: string;
}): ExifParseResult {
  const now = new Date();
  const dateStr = formatXiaomiDate(now);

  const w = details?.width || 1200;
  const h = details?.height || 1600;
  const isPortrait = h > w * 1.15;
  const isUltraWide = w > h * 1.5;

  if (isPortrait) {
    // Leica 50mm / 75mm Summilux Portrait Profile
    return {
      exif: {
        focalLength: '50mm',
        fNumber: 'f/1.4',
        exposureTime: '1/120s',
        iso: 'ISO100',
        lensModel: 'LEICA VARIO-SUMMILUX 1:1.9-2.2/14-75 ASPH.',
      },
      dateStr,
      model: 'Xiaomi 13 Pro',
      isAiEstimated: true,
      lensModel: 'LEICA VARIO-SUMMILUX 1:1.9-2.2/14-75 ASPH.',
    };
  }

  if (isUltraWide) {
    // Leica 12mm / 14mm Ultra-Wide Profile
    return {
      exif: {
        focalLength: '14mm',
        fNumber: 'f/2.2',
        exposureTime: '1/500s',
        iso: 'ISO50',
        lensModel: 'LEICA VARIO-SUMMILUX 1:1.63-2.5/12-120 ASPH.',
      },
      dateStr,
      model: 'Xiaomi 14 Ultra',
      isAiEstimated: true,
      lensModel: 'LEICA VARIO-SUMMILUX 1:1.63-2.5/12-120 ASPH.',
    };
  }

  // 1-inch sensor 23mm Leica Summilux Default Profile
  return {
    exif: {
      focalLength: '23mm',
      fNumber: 'f/1.6',
      exposureTime: '1/60s',
      iso: 'ISO125',
      lensModel: 'LEICA VARIO-SUMMILUX 1:1.9-2.2/14-75 ASPH.',
    },
    dateStr,
    model: 'Xiaomi 13 Pro',
    isAiEstimated: true,
    lensModel: 'LEICA VARIO-SUMMILUX 1:1.9-2.2/14-75 ASPH.',
  };
}

/**
 * Extracts real camera EXIF from uploaded File/Blob.
 * If EXIF is absent or was generated by AI, generates realistic Xiaomi Leica Summilux parameters.
 */
export async function parsePhotoExif(
  file: File | Blob,
  imageDimensions?: { width?: number; height?: number }
): Promise<ExifParseResult> {
  const fallback = estimateAiExif({
    width: imageDimensions?.width,
    height: imageDimensions?.height,
    filename: file instanceof File ? file.name : undefined,
  });

  try {
    const data = await exifr.parse(file, {
      pick: [
        'Make',
        'Model',
        'FocalLength',
        'FNumber',
        'ExposureTime',
        'ISO',
        'DateTimeOriginal',
        'CreateDate',
        'ModifyDate',
        'LensModel',
        'Software',
      ],
    });

    // Check if EXIF is completely missing or looks like AI generated
    const software = String(data?.Software || '').toLowerCase();
    const isAiSoftware =
      software.includes('midjourney') ||
      software.includes('stable diffusion') ||
      software.includes('comfyui') ||
      software.includes('novelai') ||
      software.includes('dall-e');

    if (!data || isAiSoftware || (!data.FocalLength && !data.FNumber && !data.ExposureTime && !data.ISO)) {
      return fallback;
    }

    let focalLength = fallback.exif.focalLength;
    if (data.FocalLength) {
      focalLength = `${Math.round(data.FocalLength)}mm`;
    }

    let fNumber = fallback.exif.fNumber;
    if (data.FNumber) {
      fNumber = `f/${data.FNumber < 10 ? Number(data.FNumber.toFixed(1)) : Math.round(data.FNumber)}`;
    }

    let exposureTime = fallback.exif.exposureTime;
    if (data.ExposureTime) {
      if (data.ExposureTime < 1) {
        exposureTime = `1/${Math.round(1 / data.ExposureTime)}s`;
      } else {
        exposureTime = `${data.ExposureTime}s`;
      }
    }

    let iso = fallback.exif.iso;
    if (data.ISO) {
      iso = `ISO${data.ISO}`;
    }

    let dateStr = fallback.dateStr;
    const rawDate = data.DateTimeOriginal || data.CreateDate || data.ModifyDate;
    if (rawDate instanceof Date) {
      dateStr = formatXiaomiDate(rawDate);
    } else if (typeof rawDate === 'string') {
      const parsed = new Date(rawDate);
      if (!isNaN(parsed.getTime())) {
        dateStr = formatXiaomiDate(parsed);
      }
    }

    let model = fallback.model;
    if (data.Model) {
      const rawModel = String(data.Model).trim();
      if (!rawModel.toLowerCase().includes('xiaomi') && data.Make?.toLowerCase().includes('xiaomi')) {
        model = `Xiaomi ${rawModel}`;
      } else {
        model = rawModel;
      }
    }

    return {
      exif: {
        focalLength,
        fNumber,
        exposureTime,
        iso,
        lensModel: data.LensModel || fallback.exif.lensModel,
      },
      dateStr,
      model,
      isAiEstimated: false,
      lensModel: data.LensModel,
    };
  } catch (err) {
    console.warn('Gagal membaca EXIF fisik, menggunakan parameter Leica AI heuristik:', err);
    return fallback;
  }
}
